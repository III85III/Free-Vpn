// Package adblock blocks dedicated advertising, tracking, and video-ad hosts
// at the network and DNS layer without breaking legitimate content streaming.
package adblock

import "strings"

// Blocked reports whether host matches a blocked advertising or tracking domain,
// including its apex and all subdomains.
func Blocked(host string) bool {
	host = strings.ToLower(strings.TrimSuffix(host, "."))
	if host == "" {
		return false
	}
	for {
		if _, ok := blockedDomains[host]; ok {
			return true
		}
		idx := strings.IndexByte(host, '.')
		if idx == -1 {
			break
		}
		host = host[idx+1:]
	}
	return false
}

// IsYouTube reports whether host belongs to YouTube or its media CDN,
// where forcing QUIC (UDP 443) to fall back to TCP HTTP/2 enables ad filtering.
func IsYouTube(host string) bool {
	host = strings.ToLower(strings.TrimSuffix(host, "."))
	return host == "youtube.com" || strings.HasSuffix(host, ".youtube.com") ||
		host == "googlevideo.com" || strings.HasSuffix(host, ".googlevideo.com")
}

